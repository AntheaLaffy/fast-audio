struct Workspace {
    #[cfg(feature = "mkl")]
    tiles: [usize; 3],
    data: Vec<f32>,
}
impl Workspace {
    fn new(strategy: ConvStrategy, core: &SpatialCore, limit: usize) -> Result<Self> {
        let [m, n, k] = core.dims;
        let tiles = if strategy == ConvStrategy::PackedMkl {
            [m.min(32), n.min(64), k.min(128)]
        } else {
            [0; 3]
        };
        let [tm, tn, tk] = tiles;
        let len = tm * tk + tk * tn + tm * tn;
        if len * size_of::<f32>() > limit {
            return Err(Error::Unsupported(format!(
                "convolution explicit workspace requires {} bytes, limit is {limit}",
                len * size_of::<f32>()
            )));
        }
        let mut data = Vec::new();
        data.try_reserve_exact(len)
            .map_err(|e| Error::Allocation(e.to_string()))?;
        data.resize(len, 0.0);
        Ok(Self {
            #[cfg(feature = "mkl")]
            tiles,
            data,
        })
    }

    fn bytes(&self) -> usize {
        self.data.capacity() * size_of::<f32>()
    }

    #[cfg(feature = "mkl")]
    fn packed(
        &mut self,
        cpu: Cpu,
        core: &SpatialCore,
        data: [&[f32]; 2],
        out: &mut [f32],
        mode: GradientMode,
    ) {
        let [m, n, k] = core.dims;
        let [tm, tn, tk] = self.tiles;
        let (pa, rest) = self.data.split_at_mut(tm * tk);
        let (pb, pc) = rest.split_at_mut(tk * tn);
        let blas = Blas {
            leading: [tk as i32, tn as i32, tn as i32],
            transposes: [0; 2],
        };
        for g in 0..core.groups {
            if k <= tk {
                for col in (0..n).step_by(tn) {
                    let cols = (n - col).min(tn);
                    core.pack_rhs_tile(data[0], g, 0, k, col, cols, tn, pb);
                    for row in (0..m).step_by(tm) {
                        let rows = (m - row).min(tm);
                        core.pack_lhs_tile(data[1], g, row, rows, 0, k, tk, pa);
                        crate::matmul::gemm(cpu, [rows, cols, k], blas, [pa, pb], pc, false);
                        core.scatter_out_tile(out, g, row, rows, col, cols, tn, pc, mode);
                    }
                }
            } else {
                for row in (0..m).step_by(tm) {
                    let rows = (m - row).min(tm);
                    for col in (0..n).step_by(tn) {
                        let cols = (n - col).min(tn);
                        for start in (0..k).step_by(tk) {
                            let depth = (k - start).min(tk);
                            core.pack_lhs_tile(data[1], g, row, rows, start, depth, tk, pa);
                            core.pack_rhs_tile(data[0], g, start, depth, col, cols, tn, pb);
                            crate::matmul::gemm(
                                cpu,
                                [rows, cols, depth],
                                blas,
                                [pa, pb],
                                pc,
                                start != 0,
                            );
                        }
                        core.scatter_out_tile(out, g, row, rows, col, cols, tn, pc, mode);
                    }
                }
            }
        }
    }
}

fn strategy(cpu: Cpu, core: &SpatialCore) -> ConvStrategy {
    #[cfg(not(feature = "mkl"))]
    let _ = core;
    match cpu {
        Cpu::Reference => ConvStrategy::Reference,
        #[cfg(feature = "mkl")]
        Cpu::Mkl { .. } => {
            if core.blas.is_some() {
                ConvStrategy::Mkl
            } else {
                ConvStrategy::PackedMkl
            }
        }
    }
}

fn execute(
    cpu: Cpu,
    core: &SpatialCore,
    strategy: ConvStrategy,
    work: &mut Workspace,
    data: [&[f32]; 2],
    out: &mut [f32],
    mode: GradientMode,
) {
    #[cfg(feature = "mkl")]
    if strategy == ConvStrategy::Mkl {
        let blas = core.blas.unwrap();
        let dims = core.blas_dims();
        for n in 0..core.batch {
            for g in 0..core.groups {
                let origins = core.slice_origins(n, g);
                let slices = if core.swapped {
                    [&data[0][origins[0]..], &data[1][origins[1]..]]
                } else {
                    [&data[1][origins[1]..], &data[0][origins[0]..]]
                };
                let acc = mode == GradientMode::Accumulate
                    || (core.op_mode == OpMode::WeightGrad && n > 0);
                crate::matmul::gemm(cpu, dims, blas, slices, &mut out[origins[2]..], acc);
            }
        }
        return;
    }
    #[cfg(feature = "mkl")]
    if strategy == ConvStrategy::PackedMkl {
        work.packed(cpu, core, data, out, mode);
        return;
    }
    #[cfg(not(feature = "mkl"))]
    let _ = (cpu, strategy, work);
    let [m, n, k] = core.dims;
    for g in 0..core.groups {
        for i in 0..m {
            for j in 0..n {
                let mut sum = 0.0;
                for r in 0..k {
                    sum += core.read_lhs(data, g, i, r) * core.read_rhs(data, g, r, j);
                }
                // SAFETY: exact layout binding and injectivity proof establish unique valid cells.
                let target = unsafe { out.get_unchecked_mut(core.write_offset(g, i, j)) };
                *target = if mode == GradientMode::Overwrite {
                    sum
                } else {
                    *target + sum
                };
            }
        }
    }
}

